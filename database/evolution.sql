ALTER TABLE order_item ADD COLUMN IF NOT EXISTS observations VARCHAR(2000) NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS order_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES service_order(id),
 occurred_at TIMESTAMP NOT NULL, actor VARCHAR(150) NOT NULL,
 event_type VARCHAR(40) NOT NULL, details VARCHAR(12000) NOT NULL
);
CREATE TABLE IF NOT EXISTS stock_movement (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 part_id BIGINT NOT NULL REFERENCES part(id), order_id BIGINT REFERENCES service_order(id),
 quantity INTEGER NOT NULL, balance INTEGER NOT NULL CHECK(balance>=0),
 occurred_at TIMESTAMP NOT NULL, actor VARCHAR(150) NOT NULL, reason VARCHAR(150) NOT NULL
);
CREATE TABLE IF NOT EXISTS password_reset (
 user_id BIGINT PRIMARY KEY REFERENCES app_user(id),
 token_hash VARCHAR(64) NOT NULL, expires_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_event_order ON order_event(order_id,id);
CREATE INDEX IF NOT EXISTS idx_movement_part ON stock_movement(part_id,id);
